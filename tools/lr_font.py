def rows(ch):
    """12 rows of 6 bits (bit 5 = leftmost pixel) for one letter."""
    art = GLYPHS[ch]
    out = [0] * 12
    for r, line in enumerate(art):
        v = 0
        for c, p in enumerate(line):
            if p == "#":
                v |= 1 << (5 - c)
        out[1 + r] = v
    return out


def pair(a, b):
    """The 12x12 glyph (12 words, bits 11-0) showing letters a and b side by side."""
    ra, rb = rows(a), rows(b)
    return [(ra[r] << 6) | rb[r] for r in range(12)]
